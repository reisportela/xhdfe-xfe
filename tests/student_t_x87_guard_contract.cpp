constexpr double kLimit = 5e-12;
constexpr unsigned short kNative = 0x037F;        // PC=64, RC=nearest, all masked
constexpr unsigned short kWindowsX64 = 0x027F;    // PC=53: Windows x64 thread start-up value
constexpr unsigned short kSingle = 0x007F;        // PC=24
constexpr unsigned short kInfinityBit = 0x127F;   // PC=53 with the legacy infinity-control bit
constexpr unsigned short kTowardZero = 0x0E7F;    // PC=53, RC=toward zero
constexpr unsigned short kDownward = 0x067F;      // PC=53, RC=down
constexpr unsigned short kUpward = 0x0A7F;        // PC=53, RC=up

[[maybe_unused]] unsigned mxcsr_controls() {
#if defined(__SSE__)
    unsigned value = 0;
    __asm__ __volatile__("stmxcsr %0" : "=m"(value) : : "memory");
    return value & ~0x3Fu;  // bits 0-5 are sticky status flags
#else
    return 0;
#endif
}

bool keeps_lsb(int bits) {
    volatile long double one = 1.0L;
    volatile long double unit = std::ldexp(1.0L, 1 - bits);
    volatile long double sum = one + unit;
    volatile long double back = sum - one;
    return back == unit;
}

// Set the control word of the calling thread and prove the resulting precision.
bool establish(unsigned short cw) {
    x87::load_control_word(cw);
    if (x87::control_word() != cw) return false;
    switch (cw & x87::kPrecisionControlMask) {
        case 0x0300: return keeps_lsb(64);
        case 0x0200: return !keeps_lsb(64) && keeps_lsb(53);
        case 0x0000: return !keeps_lsb(53) && keeps_lsb(24);
        default: return false;
    }
}

[[maybe_unused]] std::uint64_t bits(double x) {
    std::uint64_t b;
    std::memcpy(&b, &x, sizeof b);
    return b;
}

struct Query {
    char kind;
    double df, arg;
};

double evaluate(const Query& q) {
    return q.kind == 'Q' ? student::inverse_survival(q.arg, q.df)
                         : student::two_sided_probability(q.arg, q.df);
}

std::vector<Query> grid() {
    std::vector<Query> g;
    for (const Reference& r : kReferences) g.push_back({r.kind, r.df, r.arg});
    std::vector<double> dfs;
    for (int i = 0; i <= 400; ++i) dfs.push_back(std::round(std::pow(10.0, 0.3 + 7.7 * i / 400.0)));
    for (int d = 138700; d <= 138800; ++d) dfs.push_back(d);
    for (int d = 130000; d <= 150000; d += 7) dfs.push_back(d);
    dfs.push_back(1e12);
    for (double df : dfs) {
        for (double tail : {0.025, 0.005, 0.05, 5e-7}) g.push_back({'Q', df, tail});
        for (double t : {1.96, 3.5, 9.338, 37.19}) g.push_back({'P', df, t});
    }
    return g;
}

int fail(const char* what, const Query& q, double got, double want, unsigned short cw) {
    std::fprintf(stderr, "FAIL: %s cw=%#06x %c df=%.17g arg=%.17g got=%a want=%a\n",
                 what, cw, q.kind, q.df, q.arg, got, want);
    return 1;
}

bool within_contract(const Reference& r, double v) {
    if (r.kind == 'P') return std::abs(v / r.value - 1.0) <= kLimit;
    return std::abs(v - r.value) <= kLimit * std::max(1.0, std::abs(r.value));
}

#ifndef XHDFE_TEST_STUDENT_T_FORCE_PROBE_FAILURE
// Every query under cw: no refusal, word and MXCSR controls intact after each
// call; bit-identical to the native results, or (directed rounding, which the
// guard deliberately keeps) inside the public contract on the references.
int run_regime(const std::vector<Query>& g, const std::vector<double>& native, unsigned short cw,
               bool bit_identical) {
    if (!establish(cw)) {
        std::fprintf(stderr, "FAIL: could not establish control word %#06x\n", cw);
        return 1;
    }
    const unsigned mx = mxcsr_controls();
    const std::size_t n_ref = sizeof kReferences / sizeof kReferences[0];
    for (std::size_t i = 0; i < g.size(); ++i) {
        double v;
        try {
            v = evaluate(g[i]);
        } catch (const std::exception& e) {
            std::fprintf(stderr, "FAIL: refusal cw=%#06x %c df=%.17g arg=%.17g: %s\n", cw, g[i].kind,
                         g[i].df, g[i].arg, e.what());
            return 1;
        }
        if (x87::control_word() != cw) return fail("control word not restored", g[i], v, native[i], cw);
        if (mxcsr_controls() != mx) return fail("MXCSR controls changed", g[i], v, native[i], cw);
        if (bit_identical ? bits(v) != bits(native[i])
                          : (i < n_ref && !within_contract(kReferences[i], v)))
            return fail(bit_identical ? "differs from native" : "outside contract", g[i], v,
                        native[i], cw);
    }
    return 0;
}
#endif

