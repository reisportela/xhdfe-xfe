// Issue #18: Student-t public entry points under the x87 precision of the
// Windows x64 host (53 bits) and other reduced or directed control words.
//
// Windows x64 starts every thread with the x87 precision control at 53 bits;
// MinGW-built code then rounds every long double operation to 53 bits.  This
// test imposes the control word itself (fldcw) in each thread, proves the
// regime (read-back AND a volatile arithmetic probe) and fails if it cannot
// establish it, so it runs identically under Linux CTest and as a native
// MinGW executable in the Windows CI.  Do not replace this with
// _controlfp(_PC_53, _MCW_PC): the Microsoft x64 CRT does not support the
// precision mask.
//
// Checks: zero refusals on a df grid that includes the 28 df refused by the
// distributed 2.30.1 Windows plugin and very large df; results bit-identical
// to the native 64-bit control word (computed first, in this process); the
// public contract against independent mpmath references (60 digits, generator
// tests/fixtures/make_student_t_x87_reference.py); the caller's complete
// control word restored after every call, including calls that throw; MXCSR
// controls unchanged (status flags may legitimately be raised by arithmetic);
// nested scopes; repeated calls; concurrent and reused threads with different
// control words.  Built twice: normally, and with
// XHDFE_TEST_STUDENT_T_FORCE_PROBE_FAILURE (fail-closed branch).  Compile with
// the production flags of xhdfe_student_t_precision.
