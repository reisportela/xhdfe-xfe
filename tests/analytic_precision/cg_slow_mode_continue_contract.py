"""F1: a slow conjugate-gradient mode is not a broken step (follow-up of lesson CG-02).

Public synthetic fixture: pyfixest's "difficult" benchmark design (data generated by
the pyfixest benchmark DGP; the model y ~ x1..x10 | indiv_id + firm_id + year is the
one of benchmark_difficult_1m_3fe.py in the same folder), read from
/srv/projetos/P008/dataset/pyfixest with its absolute path. No data are copied into
the repository. The test is SKIPPED (not failed) when the file is absent or when no
CUDA device is visible.

Scope (measured 07nov2026): the rule fires on the CUDA Comparable CG route; with the
1 M file at tol 1e-10 the guard meets regular slow modes (lambda_p >= 0.0015). No
pyfixest fixture reaches the CPU CG, so the CPU fit is the reference here.

The CUDA route on this file is not deterministic: the IT accelerator may converge
(then the LSMR tail runs and no CG stage exists) or hand over to the CG stage. Inside
the CG a lane may stop deferring (no 10 % step progress in 32 consecutive deferrals,
slow-mode-stalled, or the 2048-deferral backstop, slow-mode-exhausted) and take the
designed restart. Hence (each fit in a fresh process, XHDFE_ACCEL_DEBUG=1,
Comparable, tol 1e-10):
* CPU Comparable, once: the reference, converged and precision-certified.
* CUDA with XHDFE_CG_SLOW_MODE_CONTINUE unset, RUNS_ON times. Every run: real GPU use,
  converged and certified, b/V within the CUDA floors of the CPU result. Every run
  that enters the CG: no step-norm breakdown (a stall or backstop breakdown followed
  by the restart is accepted and counted). At least one run converges in the CG stage without restart.
  Runs on the IT+LSMR route are recorded and skipped for the CG assertions.
* CUDA with XHDFE_CG_SLOW_MODE_CONTINUE=0, up to RUNS_OFF times until one enters the
  CG: that run takes the 2.30.1 restart path (step-norm breakdown, CG stage ending
  converged=0, no deferral). Every run: GPU use, certified, CPU comparisons.
CUDA floors: |db_j| <= 1e-9*max(1,|b_j|), |dV_jk| <= 1e-8*sqrt(V_jj*V_kk). Extra: b of
the first CG-converged ON run and of the OFF restart run agree to 1e-12 relative.
The output records the route of every run.

Usage: cg_slow_mode_continue_contract.py --module PATH.so [--data PARQUET]
                                         [--output result.json]
The module must be a CUDA-enabled build (it also runs the CPU reference).
"""
import argparse
import collections
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

DEFAULT_DATA = '/srv/projetos/P008/dataset/pyfixest/benchmark_difficult_n1000000_k10.parquet'
TOL = 1e-10
B_FLOOR = 1e-9
V_FLOOR = 1e-8
B_ON_OFF = 1e-12
RUNS_ON = 6
RUNS_OFF = 6
CONTINUE = re.compile(r'\[ACCEL cuda CG slow-mode-continue ')
BREAKDOWN = re.compile(r'\[ACCEL cuda CG breakdown stage=step-norm ')
EXHAUSTED = re.compile(r'\[ACCEL cuda CG breakdown stage=slow-mode-exhausted ')
STALLED = re.compile(r'\[ACCEL cuda CG breakdown stage=slow-mode-stalled ')
FINAL = re.compile(r'\[ACCEL cuda CG iters=(\d+) converged=(\d) deferred=(\d+)\]')


def worker(module, backend, data, out):
    import importlib.util
    import numpy as np
    import pandas as pd
    spec = importlib.util.spec_from_file_location('py_hdfe_v11', module)
    core = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(core)
    xs = ['x%d' % i for i in range(1, 11)]
    frame = pd.read_parquet(data, columns=['y', *xs, 'indiv_id', 'firm_id', 'year'])
    fac = lambda s: pd.factorize(s, sort=True)[0].astype(np.int32)
    y = frame['y'].to_numpy(np.float64)
    X = np.asfortranarray(frame[xs].to_numpy(np.float64))
    fes = [fac(frame[c]) for c in ('indiv_id', 'firm_id', 'year')]
    clusters = fac(frame['indiv_id'])
    del frame
    reg = core.HdfeRegressor(se_type='cluster', tol=TOL, num_threads=4,
                             tolerance_mode='reghdfe-comparable')
    reg.fit(y, X, fes=fes, clusters=clusters)
    Path(out).write_text(json.dumps(dict(
        b=[float(v) for v in np.asarray(reg.coef_)],
        V=np.asarray(reg.covariance_).tolist(),
        converged=bool(reg.converged_), certified=bool(reg.precision_certified_),
        abs_residual_rel=float(reg.abs_residual_rel_), iterations=int(reg.num_iterations_),
        method=int(reg.absorption_method_used), gpu_used=bool(reg.gpu_used_))))


def cuda_device_visible():
    smi = shutil.which('nvidia-smi')
    if smi is None:
        return False
    try:
        run = subprocess.run([smi, '-L'], capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return False
    return run.returncode == 0 and 'GPU' in run.stdout


def route(result):
    """IT+LSMR (no CG stage), CG converged, CG stall/backstop + restart, or CG step-norm."""
    finals = result['cg_finals']
    if not finals:
        return 'it_lsmr'
    if result['breakdowns'] > 0:
        return 'cg_step_norm'
    if result['stalled'] > 0:
        return 'cg_stalled_restart'
    if result['exhausted'] > 0:
        return 'cg_exhausted_restart'
    if all(f[1] == 1 for f in finals):
        return 'cg_converged'
    return 'cg_other'


def fit(args, backend, switch_off, directory, label):
    env = dict(os.environ, XHDFE_ACCEL_DEBUG='1', XHDFE_GPU_BACKEND=backend,
               XHDFE_ABSORPTION_CACHE_MODE='off')
    env.pop('XHDFE_CG_SLOW_MODE_CONTINUE', None)
    if switch_off:
        env['XHDFE_CG_SLOW_MODE_CONTINUE'] = '0'
    out = directory / f'{label}.json'
    run = subprocess.run([sys.executable, '-B', __file__, '--worker', str(args.module), backend,
                          args.data, str(out)], env=env, capture_output=True, text=True, timeout=1800)
    if run.returncode != 0:
        raise RuntimeError(f'{label} worker failed: ' + run.stderr[-2000:])
    result = json.loads(out.read_text())
    result.update(label=label, continues=len(CONTINUE.findall(run.stderr)),
                  breakdowns=len(BREAKDOWN.findall(run.stderr)),
                  exhausted=len(EXHAUSTED.findall(run.stderr)),
                  stalled=len(STALLED.findall(run.stderr)),
                  cg_finals=[tuple(map(int, m.groups())) for m in FINAL.finditer(run.stderr)])
    result['route'] = route(result)
    return result


def against(reference, candidate):
    import numpy as np
    b0, b = np.asarray(reference['b']), np.asarray(candidate['b'])
    V0, V = np.asarray(reference['V']), np.asarray(candidate['V'])
    scale = np.sqrt(np.outer(np.diag(V0), np.diag(V0)))
    return (float(np.max(np.abs(b - b0) / (B_FLOOR * np.maximum(1.0, np.abs(b0))))),
            float(np.max(np.abs(V - V0) / (V_FLOOR * scale))))


def main():
    if len(sys.argv) > 1 and sys.argv[1] == '--worker':
        worker(*sys.argv[2:6])
        return 0
    import tempfile
    import numpy as np
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--module', type=Path, required=True)
    p.add_argument('--data', default=DEFAULT_DATA)
    p.add_argument('--output', type=Path)
    args = p.parse_args()
    args.module = args.module.resolve()
    skip = None
    if not Path(args.data).is_file():
        skip = 'fixture absent: ' + args.data
    elif not cuda_device_visible():
        skip = 'no visible CUDA device'
    if skip:
        report = dict(status='SKIP', reason=skip)
        if args.output:
            args.output.write_text(json.dumps(report, indent=2) + '\n')
        print(json.dumps(report))
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        cpu = fit(args, 'cpu', False, Path(tmp), 'cpu')
        on = [fit(args, 'cuda', False, Path(tmp), f'on_{i}') for i in range(1, RUNS_ON + 1)]
        off = []
        for i in range(1, RUNS_OFF + 1):
            off.append(fit(args, 'cuda', True, Path(tmp), f'off_{i}'))
            if off[-1]['route'] != 'it_lsmr':
                break
    failures = []
    if not (cpu['converged'] and cpu['certified'] and not cpu['gpu_used']):
        failures.append('cpu reference not converged/certified on the CPU')
    for r in on + off:
        rb, rv = against(cpu, r)
        r.update(b_ratio=rb, V_ratio=rv)
        if not (r['gpu_used'] and r['converged'] and r['certified']):
            failures.append(f"{r['label']}: no GPU use or not converged/certified")
        if rb > 1 or rv > 1:
            failures.append(f"{r['label']}: outside the CUDA floors against the CPU (b {rb:.3g}, V {rv:.3g})")
    for r in on:
        if r['route'] in ('cg_step_norm', 'cg_other'):
            failures.append(f"{r['label']}: CG route {r['route']} with the switch on")
    converged_on = [r for r in on if r['route'] == 'cg_converged']
    if not converged_on:
        failures.append('no switch-on run converged in the CG stage without restart')
    elif not any(f[2] > 0 for f in converged_on[0]['cg_finals']) and \
            not any(r['continues'] > 0 for r in converged_on):
        failures.append('no slow-mode deferral observed in the converged CG runs')
    off_cg = [r for r in off if r['route'] != 'it_lsmr']
    rel_b = None
    if not off_cg:
        failures.append('the switch-off run never entered the CG stage')
    else:
        o = off_cg[0]
        if not (o['route'] == 'cg_step_norm' and o['continues'] == 0 and
                any(f[1] == 0 for f in o['cg_finals'])):
            failures.append(f"{o['label']}: switch off did not take the restart path ({o['route']})")
        if converged_on:
            b_on, b_off = np.asarray(converged_on[0]['b']), np.asarray(o['b'])
            rel_b = float(np.max(np.abs(b_on - b_off) / np.abs(b_off)))
            if rel_b > B_ON_OFF:
                failures.append(f'b ON vs OFF {rel_b:.3g} > {B_ON_OFF}')
    strip = lambda r: {k: v for k, v in r.items() if k not in ('b', 'V')}
    report = dict(status='FAIL' if failures else 'PASS', data=args.data, module=str(args.module),
                  tol=TOL, failures=failures,
                  routes_on=dict(collections.Counter(r['route'] for r in on)),
                  routes_off=dict(collections.Counter(r['route'] for r in off)),
                  rel_b_on_vs_off=rel_b, cpu=strip(cpu),
                  on=[strip(r) for r in on], off=[strip(r) for r in off])
    if args.output:
        args.output.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({k: report[k] for k in ('status', 'failures', 'routes_on', 'routes_off',
                                             'rel_b_on_vs_off')}))
    return 0 if report['status'] == 'PASS' else 1


if __name__ == '__main__':
    raise SystemExit(main())
